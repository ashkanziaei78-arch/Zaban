--  نسخهٔ ۷ — چند-نقشی و زمینهٔ فعال
--
--  تا اینجا هر کاربر در هر آموزشگاه دقیقاً یک نقش داشت، و قید یکتای
--  uq_member همین را تحمیل می‌کرد. از اینجا یک نفر می‌تواند هم‌زمان
--  مدیر یک آموزشگاه، مدرس آموزشگاه دیگر و زبان‌آموز سومی باشد — یا
--  حتی در یک آموزشگاه چند نقش داشته باشد.
--
--  ⚠ برخلاف نسخهٔ ۶، این مهاجرت برگشت‌ناپذیر است: به‌محض برداشتن
--  uq_member، عضویت تکراری ساخته می‌شود و بازگرداندن قید دیگر ممکن
--  نیست مگر با حذف داده. پس ترتیب معکوس است — اول قید تازه ساخته و
--  تأیید می‌شود، بعد قدیمی برداشته می‌شود. و پیش از اجرا پشتیبان کامل.
--
--  چرا زمینهٔ فعال روی نشست و نه در مرورگر: اگر سرور هنگام بررسی
--  دسترسی بپرسد «آیا این کاربر جایی نقش مدرس دارد؟» به‌جای «آیا نقش
--  فعالش مدرس است؟»، کسی که در نمای زبان‌آموز نشسته می‌تواند با یک
--  درخواست دستی دادهٔ مدرس را بخواند. سوییچ ظاهری در رابط، بدون تغییر
--  زمینه در سرور، هیچ حفاظتی نیست.
-- ═══════════════════════════════════════════════════════════════════


-- ── گام ۱: هیچ عضویتی نباید role_id تهی داشته باشد ────────────────
-- اگر این عدد صفر نبود، مهاجرت نسخهٔ ۶ ناقص مانده و ادامه ندهید.
UPDATE membership SET role_id = CASE role
  WHEN 'manager' THEN 'r_manager'
  WHEN 'teacher' THEN 'r_teacher'
  ELSE 'r_student' END
 WHERE role_id IS NULL;


-- ── گام ۲: قید تازه پیش از برداشتن قدیمی ──────────────────────────
-- ترتیب عمدی است. اگر ساخت این قید به‌خاطر دادهٔ تکراری شکست بخورد،
-- هنوز هیچ‌چیز خراب نشده و uq_member سر جایش است.
ALTER TABLE membership
  ADD UNIQUE KEY uq_member_role (institute_id, user_id, role_id);


-- ── گام ۳: حالا قید تک‌نقشی برداشته می‌شود ────────────────────────
ALTER TABLE membership DROP INDEX uq_member;


-- ── گام ۴: role_id از این پس اجباری است ───────────────────────────
ALTER TABLE membership MODIFY COLUMN role_id CHAR(32) NOT NULL;


-- ── گام ۵: کلید خارجی به نقش ──────────────────────────────────────
-- بعد از NOT NULL شدن اضافه می‌شود تا اگر داده‌ای ناسازگار بود، در
-- گام قبل معلوم شده باشد.
ALTER TABLE membership
  ADD CONSTRAINT fk_member_role FOREIGN KEY (role_id) REFERENCES role(id);


-- ── گام ۶: ایندکس برای انتخابگر زمینه ─────────────────────────────
-- انتخابگر نقش در هر بارگذاری پنل، همهٔ عضویت‌های فعال کاربر را
-- می‌خواند. بدون این ایندکس، پیمایش کامل جدول است.
ALTER TABLE membership
  ADD KEY ix_member_active (user_id, status, expires_at);
