-- ── کلاس: بازه و تاریخ آزمون‌ها ────────────────────────────────────
--
-- total_sessions می‌گفت کلاس چند جلسه دارد، ولی نه از کِی تا کِی. برای
-- «چند جلسه مانده» باید جلسه‌های برگزارشده را می‌شمردیم و برای «کلاس
-- تمام شده؟» هیچ راهی نبود جز حدس.
--
-- ends_on هم تاریخ پایان است هم تاریخ انقضا: بعد از آن، کلاس در
-- فهرست‌های جاری نمی‌آید ولی داده‌اش می‌ماند — کارنامه و حضور و غیاب
-- سال‌ها بعد هم باید خوانده شود.
--
-- تاریخ‌ها میلادی ذخیره و شمسی نمایش داده می‌شوند (بند P.2).
ALTER TABLE klass
  ADD COLUMN starts_on  DATE NULL,
  ADD COLUMN ends_on    DATE NULL,
  ADD COLUMN midterm_on DATE NULL,
  ADD COLUMN final_on   DATE NULL;

-- پرس‌وجوی داغ: «کلاس‌های جاری این آموزشگاه»
ALTER TABLE klass ADD KEY ix_class_window (institute_id, ends_on);


-- ── تکلیف: تمدید مهلت ──────────────────────────────────────────────
--
-- مدرس امروز برای تمدید مهلت، due_at را عوض می‌کند. سه چیز از دست
-- می‌رود: مهلت اصلی، اینکه اصلاً تمدید شده، و اینکه چرا. بعد وقتی
-- زبان‌آموزی می‌پرسد «مگر تا جمعه نبود؟» جوابی نیست.
--
-- extended_to جدا می‌نشیند تا due_at دست‌نخورده بماند. تأخیر هم از
-- روی مهلت *مؤثر* حساب می‌شود، نه اصلی — کسی که در مهلت تمدیدشده
-- تحویل داده، دیرکرد ندارد.
ALTER TABLE assignment
  ADD COLUMN extended_to   DATETIME     NULL,
  ADD COLUMN extended_by   CHAR(32)     NULL,
  ADD COLUMN extend_note   VARCHAR(255) NULL,
  ADD COLUMN extended_at   DATETIME     NULL;


-- ── آموزشگاه: بازهٔ فعالیت ─────────────────────────────────────────
--
-- قرارداد آموزشگاه از تاریخی تا تاریخی است. تا امروز فقط
-- status = 'suspended' بود که کسی باید دستی می‌زد — یعنی روزی که
-- قرارداد تمام می‌شد، اگر کسی یادش می‌رفت، آموزشگاه سال‌ها رایگان
-- کار می‌کرد.
--
-- active_to نه خودش چیزی را می‌بندد و نه باید ببندد: بستنِ خودکار کارِ
-- دستور super.php است که هم دمو را جارو می‌کند هم این را. ستون فقط
-- می‌گوید قرارداد تا کِی است.
ALTER TABLE institute
  ADD COLUMN active_from DATE NULL,
  ADD COLUMN active_to   DATE NULL;

ALTER TABLE institute ADD KEY ix_inst_active_to (active_to);
