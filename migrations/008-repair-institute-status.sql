--  ۰۰۸ — ترمیم: ستون‌های جامانده از نسخهٔ ۴
--
--  روی سرور زنده کشف شد که جدول institute ستون‌های status و
--  suspended_reason را ندارد، در حالی که کد از نسخهٔ ۴ به بعد رویشان
--  حساب می‌کند. نتیجه‌اش دو اکشن ۵۰۰ در پنل سوپرادمین بود:
--  institutes.list و stats.
--
--  چرا جا ماند: این دو ALTER بخشی از «نسخهٔ ۴» بودند و به انتهای
--  schema.mysql.sql اضافه شدند، ولی نصب‌کننده فقط یک‌بار و در لحظهٔ
--  نصب اجرا می‌شود. پایگاه دادهٔ زنده پیش از آن ساخته شده بود، پس
--  ALTERهای بعدی هرگز به آن نرسیدند. نسخهٔ ۵ (jitsi_enabled) دستی
--  اجرا شد و هست؛ نسخهٔ ۴ فراموش شده بود.
--
--  درس: هر ALTER تازه‌ای که به انتهای اسکیما اضافه می‌شود، باید یک
--  فایل مهاجرت جدا هم داشته باشد — وگرنه فقط روی نصب‌های تازه اثر
--  می‌کند و پایگاه‌های موجود بی‌صدا عقب می‌مانند.
--
--  کاملاً افزودنی و بی‌خطر. اگر ستون‌ها از قبل باشند، خطای
--  Duplicate column می‌دهد که یعنی این فایل لازم نبوده.
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE institute ADD COLUMN status           VARCHAR(16)  NOT NULL DEFAULT 'active';
ALTER TABLE institute ADD COLUMN suspended_reason VARCHAR(255) NULL;
